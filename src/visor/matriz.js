/** Quantos caracteres a linha de cima mostra. */
export const CARACTERES = 16
/** Cada caractere ocupa cinco colunas de pontos e uma de espaço. */
export const COLUNAS_POR_CARACTERE = 6

const glifo = (c) => FONTE[c] ?? FONTE['?']

/**
 * O pedaço da conta que cabe na linha: o FIM dela, como no visor de verdade, com a seta da
 * esquerda acesa quando o começo ficou de fora. O cursor, quando pedido, ocupa uma posição.
 */
export function recorteDaLinha(texto, { caracteres = CARACTERES, cursor = false } = {}) {
  const todos = [...String(texto ?? '')]
  const cabem = cursor ? caracteres - 1 : caracteres
  const cortado = todos.length > cabem
  const visiveis = cortado ? todos.slice(-cabem) : todos
  return { visiveis, cortado, posicaoDoCursor: cursor ? visiveis.length : -1 }
}

/**
 * O `d` de um SVG com os pontos acesos dos caracteres, lado a lado a partir da esquerda.
 * Cada ponto é um quadrado de lado `ponto` numa grade de passo 1.
 */
export function caminhoDosPontos(caracteres, { ponto = 0.78 } = {}) {
  const partes = []
  caracteres.forEach((c, i) => {
    const linhas = glifo(c)
    const x0 = i * COLUNAS_POR_CARACTERE
    linhas.forEach((linha, y) => {
      for (let x = 0; x < 5; x++) {
        if (linha[x] === '1') partes.push(`M${x0 + x} ${y}h${ponto}v${ponto}h-${ponto}Z`)
      }
    })
  })
  return partes.join('')
}

/** A grade inteira de pontos apagados (o "fantasma" do LCD), para `caracteres` posições. */
export function caminhoDaGrade(caracteres = CARACTERES, { ponto = 0.78 } = {}) {
  const partes = []
  for (let i = 0; i < caracteres; i++) {
    const x0 = i * COLUNAS_POR_CARACTERE
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 5; x++) partes.push(`M${x0 + x} ${y}h${ponto}v${ponto}h-${ponto}Z`)
    }
  }
  return partes.join('')
}
